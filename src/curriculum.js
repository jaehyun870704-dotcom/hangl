/** 획을 만들 수 있는 것만 남긴다 (겹자음·겹모음까지 다룰 수 있지만 혹시 모를 것 대비) */
function buildText(id, text, emoji) {
  const res = textStrokes(text);
  if (!res) return null;
  return { id, text, label: text, word: text, emoji, strokes: res.strokes, scale: res.scale };
}

const stage1 = JAMO.map((j) => ({
  id: j.id, text: j.ch, label: j.ch, name: j.name,
  word: j.word, emoji: j.emoji, strokes: j.strokes, scale: 1,
}));

const stage2 = SYLLABLES.map((ch, i) => buildText(`s2-${i}`, ch, null)).filter(Boolean);

// 낱말은 획이 적은 것부터 — 네 살에게 «다람쥐»(18획)를 먼저 주면 안 된다
const stage3 = WORDS
  .map(([w, e], i) => buildText(`s3-${i}`, w, e))
  .filter(Boolean)
  .sort((a, b) => a.strokes.length - b.strokes.length || [...a.text].length - [...b.text].length);

