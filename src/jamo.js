/** 원형 획 생성 (화면 좌표계에서 반시계 방향이 기본 — 한글 ㅇ 필기 방향) */
function circle(cx, cy, r, startDeg = -90, ccw = true, steps = 44) {
  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const deg = startDeg + (ccw ? -360 : 360) * (i / steps);
    const a = (deg * Math.PI) / 180;
    pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  return pts;
}

